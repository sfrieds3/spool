// Package history is Spool's transport-independent local session service.
// The CLI (and later MCP and SSH endpoints) call List and Read and serialize
// the returned values; no interface re-implements harness parsing.
package history

import (
	"encoding/json"
	"fmt"
)

// ResponseVersion is the version of every JSON response envelope.
const ResponseVersion = 1

